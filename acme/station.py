# Name: station.py
# Nodes: ALL (/opt/acme/acme/)
# Purpose: Manufactures and provisions the incoming sign requests and outputs the certificates
# Notes:
#   - Consists of the following:
#       - trust             - load Cert_ACME and the update certificates
#       - accept            - take a signing request from a console or server
#       - new-cartridge     - generate a cartridge's keys and request here
#       - export-requests   - hand pending requests to the offline issuer
#       - receive           -  check returned certificates against the requests
#       - export            - hand a device its certificates (console/server) or its complete image (cartridge)
#       - erase             - destroy the station's copy of a cartridge's keys
# ===================================================================
# Libraries

import argparse, os, shutil, sys
from pathlib import Path

from . import cert as C
from . import crypto 
from . import csr as R
from . import keystore as K
from .cert import CertError, Role

DEFAULT_HOME = "/var/lib/acme-station"
TRUST_FILES = ("root.cert",) + K.UPDATE_CERTS

# ===================================================================
# Template

class StationError(Exception):
    pass

class Station:
    def __init__(self, home):
        self.home = Path(home)
        self.trust_dir = self.home / "trust"
        self.requests = self.home / "requests"
        self.certs = self.home / "certs"
        self.work = self.home / "work"

    def _mk(self):
        for d in (self.trust_dir, self.requests, self.certs, self.work):
            d.mkdir(mode=0o700, parents=True, exist_ok=True)
        # end

    def anchor(self, now=None) -> C.Certificate:
        try:
            raw = (self.trust_dir / "root.cert").read_bytes()
        except OSError as e:
            raise StationError("No trust anchor, run trust first") from e
        return C.load_trust_anchor(raw, now=now)
        # end

    def trust(self, src, now=None) -> None:
        src = Path(src)
        root_raw = (src / "root.cert").read_bytes()
        anchor = C.load_trust_anchor(root_raw, now=now)
        have = self.trust_dir / "root.cert"
        if have.exists() and have.read_bytes() != root_raw:
            raise StationError("a different trust anchor is already installed")
        ups = [(src / n).read_bytes() for n in K.UPDATE_CERTS]
        for u in ups:
            C.verify_cert(u, anchor, Role.UPDATE, now=now)
        self._mk()
        for name, raw in zip(TRUST_FILES, [root_raw] + ups):
            (self.trust_dir / name).write_bytes(raw)
        # end

    def accept(self, csr_raw: bytes) -> R.Request:
        req = R.parse_csr(csr_raw)
        if req.role is Role.CARTRIDGE:
            raise StationError("Cartridge keys are generated by the station")
        self._queue(req, csr_raw)
        return req
        # end

    def _queue(self, req: R.Request, csr_raw: bytes) -> None:
        self._mk()
        name = req.serial.hex()
        if (self.requests / f"{name}.csr").exists() or (self.certs / f"{name}.cert").exists():
            raise StationError(f"serial {name} already seen") 
        (self.requests / f"{name}.csr").write_bytes(csr_raw)
        # end

    def new_cartridge(self, model: str) -> R.Request:
        self._mk()
        serial = crypto.random(C.SERIAL_LEN)
        csr_raw = K.DeviceImage(self.work / serial.hex()).create(Role.CARTRIDGE, model, serial)
        req = R.parse_csr(csr_raw)
        self._queue(req, csr_raw)
        return req
        # end

    def export_requests(self, dest) -> int:
        dest = Path(dest)
        dest.mkdir(parents=True, exist_ok=True)
        n = 0
        for f in sorted(self.requests.glob("*.csr")) if self.requests.exists() else []:
            (dest / f.name).write_bytes(f.read_bytes())
            n += 1
        return n
        # end

    def receive(self, src, now=None):
        # Match returned certs to pending requests and verify them
        src, anchor = Path(src), self.anchor(now)
        done, failed = [], []
        for f in sorted(self.requests.glob("*.csr")):
            name = f.stem
            cert_path = src / f"{name}.cert"
            if not cert_path.is_file():
                continue
            try:
                req = R.parse_csr(f.read_bytes())
                raw = cert_path.read_bytes()
                cert = C.verify_cert(raw, anchor, req.role, now=now)
                if (cert.serial, cert.model, cert.sign_pk, cert.enc_pk) != (req.serial, req.model, req.sign_pk, req.enc_pk):
                    raise StationError("certificate does not match request")
                img = K.DeviceImage(self.work / name)
                if img.state() == "pending":
                    img.install(raw, anchor.raw, now=now)
                (self.certs / f"{name}.cert").write_bytes(raw)
                f.unlink()
                done.append(name)
            except (CertError, StationError, K.KeystoreError) as e:
                failed.append((name, str(e)))
        return done, failed
        # end

    def export(self, serial_hex: str, dest) -> str:
        cert = self.certs / f"{serial_hex}.cert"
        if not cert.is_file():
            raise StationError(f"No cert for {serial_hex}")
        dest = Path(dest)
        dest.mkdir(parents=True, exist_ok=True)
        work = self.work / serial_hex
        if work.is_dir():
            for name in K.ALL_FILES:
                if (work / name).is_file():
                    shutil.copyfile(work / name, dest / name)
            return "cartridge image"
        (dest / "device.cert").write_bytes(cert.read_bytes())
        for name in TRUST_FILES:
            (dest / name).write_bytes((self.trust_dir / name).read_bytes())
        return "certificates"
        # end

    def erase(self, serial_hex: str) -> list[str]:
        work = self.work / serial_hex
        if not work.is_dir():
            raise StationError(f"no cartridge image for {serial_hex}")
        gone = K.DeviceImage(work).erase()
        shutil.rmtree(work)
        return gone
        # end

def wipe_dir(path) -> None:
    # wipes an exported transfer directory after is has been collected
    path = Path(path)
    if path.is_dir():
        for f in path.iterdir():
            if f.is_file():
                K.wipe(f)
        shutil.rmtree(path)
    # end

# ===================================================================
# Main
def main(argv=None) -> int:
    p = argparse.ArgumentParser(prog="acme-station")
    p.add_argument("--home", default=os.environ.get("ACME_STATION_HOME", DEFAULT_HOME))
    sub = p.add_subparsers(dest="cmd", required=True)
    for name, args in (("trust", ["dir"]), ("accept", ["csr"]),
                       ("export-requests", ["dir"]), ("receive", ["dir"]),
                       ("export", ["serial", "dir"]), ("erase", ["serial"]),
                       ("wipe-dir", ["dir"]), ("list", [])):
        s = sub.add_parser(name)
        for arg in args:
            s.add_argument(arg)
    s = sub.add_parser("new-cartridge")
    s.add_argument("--model", required=True)
    a = p.parse_args(argv)
    st = Station(a.home)
    os.umask(0o077)
    try:
        if a.cmd == "trust":
            st.trust(a.dir)
            print(f"trust anchor {st.anchor().serial_hex} installed")
        elif a.cmd == "accept":
            req = st.accept(Path(a.csr).read_bytes())
            print(f"serial={req.serial.hex()}")
        elif a.cmd == "new-cartridge":
            st.anchor()
            print(f"serial={st.new_cartridge(a.model).serial.hex()}")
        elif a.cmd == "export-requests":
            print(f"{st.export_requests(a.dir)} request(s) exported")
        elif a.cmd == "receive":
            done, failed = st.receive(a.dir)
            for n in done:
                print(f"VERIFIED {n}")
            for n, why in failed:
                print(f"REJECTED {n}: {why}", file=sys.stderr)
            return 1 if failed else 0
        elif a.cmd == "export":
            print(f"exported {st.export(a.serial, a.dir)} to {a.dir}")
        elif a.cmd == "erase":
            print(f"station copy of {a.serial} erased: " + ", ".join(st.erase(a.serial)))
        elif a.cmd == "wipe-dir":
            wipe_dir(a.dir)
        elif a.cmd == "list":
            for kind, d, ext in (("pending", st.requests, "csr"), ("issued", st.certs, "cert")):
                for f in sorted(d.glob(f"*.{ext}")) if d.exists() else []:
                    held = " (keys held)" if (st.work / f.stem).is_dir() else ""
                    print(f"{kind:<8} {f.stem}{held}")
    except (StationError, K.KeystoreError, CertError, OSError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    return 0
    # end

if __name__ == "__main__":
    sys.exit(main())